import { SKILL } from '../../../../core/skill/skill.js';
import type { EnablePropMap } from '../../../../core/skill/skill.js';

// ============================================================
// 摘星功 — 星宿派高级轻功
// 《天龙八部》中星宿派盘踞星宿海，丁春秋自号「星宿老仙」。
// 摘星功取其「手可摘星辰」之意，身法诡异阴柔，飘飘然似仙，实则暗藏杀机。
// ============================================================

export default class extends SKILL {
    name = '摘星功';
    id = 'zhaixinggong';
    grade = 2;

    desc =
        '星宿派的轻功身法。星宿海地势高绝，夜间星辰仿佛伸手可摘，丁春秋遂以「摘星」为名创此轻功。身法看似仙气飘飘，实则诡异莫测。';
    can_enables = ['dodge'];
    dodge_actions = [
        '$n怪笑一声，袍袖如蝠翼般展开，身形借力拔起——「<MAG>九天揽月</MAG>」！整个人如一只巨大的毒蝠凌空盘旋，$N的攻势尽数落空。\n',
        '只见$n身形一矮，整个人如一片枯叶般贴着地面滑出丈外，姿态说不出的诡异阴森。\n',
        '$n阴恻恻一笑：「<HIM>危楼高百尺，手可摘星辰</HIM>。」话音未落，身形已如轻烟般袅袅升起，$N一击落空。\n',
        '$n足尖在地上轻轻一点，身形向后飘飞之际宽大的袍袖迎风鼓荡，袖中寒光闪烁，$N不由得心头一凛，招式已偏了三分。\n',
        '却见$n身形滴溜溜一转，整个人如陀螺般旋转上升，在空中连转数匝，$N看得眼花缭乱，招式早已偏了准头。\n',
        '$n身子如没有骨头般的一扭，竟从一个绝不可能的方位闪了出去，$N这凌厉一击贴着$n的衣角擦过，堪堪落空。\n',
    ];

    query_enable_prop(lv: number): EnablePropMap {
        return {
            dodge: {
                ds: 100 + Math.floor((lv * 17) / 10),
                dex: 10 + Math.floor(lv / 4),
            },
        };
    }
}
